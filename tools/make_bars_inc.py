#!/usr/bin/env python3
"""make_bars_inc.py — extract ui_draw_desktop_bars() into tests/bars.inc.

    python3 tools/make_bars_inc.py shell/ui.c tests/bars.inc
    python3 tools/make_bars_inc.py fs/update.c tests/vercmp.inc ver_parse ver_cmp

tests/test_chrome.c compiles the REAL chrome function natively against a fake
VGA and checks where every column lands in each text mode.  The v0.7.18 source
zip shipped a test that did `#include "bars.inc"` without shipping bars.inc,
so the suite could not compile at all and the claimed 42/42 was unverifiable.

Generating it — rather than committing a copy — is deliberate.  A hand-copied
duplicate of a function under test drifts from the original, and silently
starts certifying code that is no longer what ships.  This project has been
bitten by exactly that (fs/update.c believing it was 0.5.9.14; $VER reading
0.7.11).  Extracting at build time means the test cannot test a stale copy.
"""
import re
import sys

FUNC = "ui_draw_desktop_bars"


def extract(src_path, func=FUNC):
    src = open(src_path, encoding="utf-8").read()
    lines = src.split("\n")

    start = None
    for i, line in enumerate(lines):
        # Any return type, with or without `static` — not just void.
        if re.match(r'^\s*(?:static\s+)?[A-Za-z_][A-Za-z0-9_ *]*?\b'
                    + re.escape(func) + r'\s*\(', line):
            start = i
            break
    if start is None:
        sys.exit("make_bars_inc.py: %s() not found in %s" % (func, src_path))

    # Walk braces from the opening line to the matching close, ignoring braces
    # inside string/char literals and comments.
    depth = 0
    opened = False
    end = None
    in_block_comment = False
    for i in range(start, len(lines)):
        line = lines[i]
        j = 0
        while j < len(line):
            two = line[j:j + 2]
            if in_block_comment:
                if two == "*/":
                    in_block_comment = False
                    j += 2
                    continue
                j += 1
                continue
            if two == "/*":
                in_block_comment = True
                j += 2
                continue
            if two == "//":
                break
            c = line[j]
            if c == '"' or c == "'":
                q = c
                j += 1
                while j < len(line):
                    if line[j] == "\\":
                        j += 2
                        continue
                    if line[j] == q:
                        break
                    j += 1
                j += 1
                continue
            if c == "{":
                depth += 1
                opened = True
            elif c == "}":
                depth -= 1
                if opened and depth == 0:
                    end = i
                    break
            j += 1
        if end is not None:
            break
    if end is None:
        sys.exit("make_bars_inc.py: unbalanced braces in %s()" % func)
    return "\n".join(lines[start:end + 1])


def main():
    if len(sys.argv) < 3:
        sys.exit("usage: make_bars_inc.py <source.c> <out.inc> [func ...]")
    src_path, out_path = sys.argv[1], sys.argv[2]
    funcs = sys.argv[3:] or [FUNC]
    bodies = [extract(src_path, f) for f in funcs]
    body = "\n\n".join(bodies)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write("/* Auto-generated by tools/make_bars_inc.py from %s — DO NOT EDIT.\n"
                "   Extracted verbatim so the test cannot certify a stale copy.\n"
                "   Functions: %s */\n\n"
                % (src_path, ", ".join(funcs)))
        f.write(body + "\n")
    print("make_bars_inc: %s -> %s (%d lines, %d function(s))"
          % (src_path, out_path, body.count("\n") + 1, len(funcs)))


if __name__ == "__main__":
    main()
