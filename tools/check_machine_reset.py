#!/usr/bin/env python3
"""check_machine_reset.py -- one file resets the machine, and only one.

This check exists because the same defect shipped in nine places at
once, and every one of them was correct-looking.

`reboot` and `poweroff` both hung the HP. Reported 20 October. Neither
was a crash: both were one write to a port that exists only in an
emulator, followed by `for(;;) cli; hlt`. On a machine where the write
does nothing, the halt is reached and the screen keeps saying
"Rebooting HavenDOS... Please wait." for ever.

  reset      outb(0x64,0xFE) pulses the 8042 reset line. That laptop
             has no 8042 -- no PS/2 port of either kind, and the
             controller is emulated in SMM, the same emulation that
             doubled every keystroke until v0.8.5.3. An emulated
             register has no reset line behind it.
  poweroff   0x604 is QEMU's ACPI PM1a_CNT, 0xB004 Bochs and older
             QEMU, 0x4004 VirtualBox. All three are emulator
             inventions. On real silicon those addresses belong to
             something else, or to nothing.

Nine copies, across five files -- kernel/main.c, shell/shell.c,
shell/login.c, shell/desktop.c and shell/iso_installer.c twice -- and
not one of them had heard of port 0xCF9, which is the register that
works. Fixing it nine times would have been the bus-label mistake
again: v0.8.3.1 put the bus name "in one place", v0.8.5.3 found a
second place, and only tools/check_bus_label.py actually stopped it.

So the words themselves are the thing being guarded. kernel/machine.c
owns every port below; anything else that writes one fails the build.

Run:  python3 tools/check_machine_reset.py
"""
import os
import re
import sys

OWNER = "kernel/machine.c"

# Ports with exactly one purpose. Any appearance in code outside the
# owner is a second reset path by definition -- none of these addresses
# is used for anything else in this tree.
PORTS = {
    "0xcf9":  "the PCI reset control register",
    "0x604":  "QEMU's ACPI PM1a_CNT (power off)",
    "0xb004": "Bochs / old QEMU ACPI PM1a_CNT (power off)",
    "0x4004": "VirtualBox ACPI PM1a_CNT (power off)",
}

# The 8042 pulse is different: port 0x64 is the keyboard controller's
# command port and drivers/keyboard.c, drivers/mouse.c and
# drivers/mode13.c all write to it legitimately. What is forbidden is
# the RESET COMMAND specifically -- 0xFE to 0x64 -- so this matches the
# write, not the port. Data tables that merely contain both bytes
# (drivers/vga.c's font, for one) cannot trip it.
PULSE_C   = re.compile(r"outb\s*\(\s*0x64\s*,\s*0xfe\s*\)", re.I)
PULSE_ASM = re.compile(r"\$\s*0xfe\s*,\s*%+al", re.I)

# The pulse written through local macros, which is how a copy of
# kernel/machine.c's own stage 3 would look if someone lifted it:
#
#     #define KBC_CMD       0x64
#     #define KBC_PULSE_RST 0xFE
#     outb(KBC_CMD, KBC_PULSE_RST);
#
# The call itself has no literals in it, so PULSE_C cannot see it. The
# DEFINITIONS do. A file that defines one macro to 0x64 and another to
# 0xFE is building the 8042 reset and nothing else -- there is no
# legitimate pairing of those two values, so this needs no exemption
# list.
DEF_64 = re.compile(r"^\s*#\s*define\s+(\w+)\s+0x64\s*$", re.I | re.M)
DEF_FE = re.compile(r"^\s*#\s*define\s+(\w+)\s+0xfe\s*$", re.I | re.M)

# What this check still cannot see, stated rather than left to be
# discovered: a pulse assembled at runtime (a port held in a variable,
# a value computed arithmetically, 0x64 and 0xFE written in decimal as
# 100 and 254) goes through. Guarding those means parsing C rather than
# grepping it, and the regression this exists to stop is a copy-paste
# of one of the nine sites that shipped -- every one of which used
# plain literals.

# Generated byte arrays: whole binaries as C initialisers, which will
# contain any byte pattern you care to name.
GENERATED = {
    "include/kernel_elf.h", "include/grub_embed.h",
    "include/grub_disk_embed.h", "include/grub_efi_embed.h",
    "include/font8x8.h", "include/font8x8_ext.h",
}

# include/machine_asm.h holds the triple fault and the halt loop, which
# are the two instructions kernel/machine.c cannot reach through io.h.
# It writes no port, so it is not an exemption from the rule -- it is
# simply the other half of the owner.
OWNER_SIDECAR = "include/machine_asm.h"

# tests/ is skipped because a suite legitimately names these ports: it
# asserts that machine_reset() writes them, so it must say which. The
# rest hold no C that runs on the machine. boot/ IS scanned -- boot.S is
# code that executes, it mentions none of these ports today, and a reset
# hidden in the bootstrap is exactly the kind of second path this check
# exists to refuse.
SKIP_DIRS = (".git", "isodir", "tests", "harness", "tools", "manual",
             "docs", "rescue", "__pycache__")


def blank_comments(text):
    """Replace comment bodies with spaces, keeping every newline, so
    line numbers survive and prose about this bug does not trip the
    check it documents."""
    out = []
    i, n = 0, len(text)
    while i < n:
        if text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            out.append("".join("\n" if c == "\n" else " "
                               for c in text[i:j]))
            i = j
        elif text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif text[i] in "\"'":
            q = text[i]
            j = i + 1
            while j < n and text[j] != q:
                j += 2 if text[j] == "\\" else 1
            j = min(j + 1, n)
            out.append(text[i:j])
            i = j
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def main():
    if not os.path.isdir("kernel"):
        sys.stderr.write("run me from the source root\n")
        return 2
    if not os.path.exists(OWNER):
        sys.stderr.write("%s is missing -- that IS the bug\n" % OWNER)
        return 2

    bad = []
    checked = 0
    for root, dirs, files in os.walk("."):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for fn in sorted(files):
            if not fn.endswith((".c", ".h", ".S")):
                continue
            rel = os.path.relpath(os.path.join(root, fn), ".").replace("\\", "/")
            if rel in (OWNER, OWNER_SIDECAR) or rel in GENERATED:
                continue
            checked += 1
            code = blank_comments(open(os.path.join(root, fn),
                                       encoding="utf-8",
                                       errors="replace").read())
            for num, line in enumerate(code.splitlines(), 1):
                low = line.lower()
                for port, what in sorted(PORTS.items()):
                    if port in low:
                        bad.append((rel, num, "port %s -- %s" % (port, what)))
                if PULSE_C.search(line) or PULSE_ASM.search(line):
                    bad.append((rel, num,
                                "the 8042 reset pulse (0xFE -> 0x64)"))

            # The same pulse built out of local macros, which leaves no
            # literals in the outb() call for the line scan above to find.
            m64 = DEF_64.search(code)
            mfe = DEF_FE.search(code)
            if m64 and mfe:
                bad.append((rel, code[:m64.start()].count("\n") + 1,
                            "the 8042 reset pulse via macros (%s=0x64 with "
                            "%s=0xFE)" % (m64.group(1), mfe.group(1))))

    if bad:
        print("check_machine_reset: the machine is reset outside %s\n" % OWNER)
        for rel, num, what in bad:
            print("  %s:%d  %s" % (rel, num, what))
        print("\n  Call machine_reset() or machine_poweroff() from")
        print("  include/machine.h instead. They try every method this")
        print("  tree knows -- 0xCF9 warm, 0xCF9 full, the 8042 pulse,")
        print("  then a triple fault -- and when all of them fail they")
        print("  say so on screen rather than halting under a message")
        print("  that claims the machine is restarting.")
        print("\n  Nine sites wrote this sequence by hand and none of them")
        print("  worked on the laptop HavenDOS dual-boots on. A tenth")
        print("  will not either.")
        return 1

    print("check_machine_reset: ok, %d files reset nothing; %s owns it"
          % (checked, OWNER))
    return 0


if __name__ == "__main__":
    sys.exit(main())
