#!/usr/bin/env python3
"""sync_emu.py -- Retro PC's emulators, from the RetroPC repo.

Since 23 Nov 2026 Retro PC lives in its own repository,
github.com/MGKFN/RetroPC, and that is where its emulators are worked
on. Kyan chose it: "RetroPC repo is the source". HavenDOS's kernel
runs the same code (Apps > Retro PC), so it copies it from there:

    python3 tools/sync_emu.py /path/to/RetroPC     copy, and stamp
    python3 tools/sync_emu.py --check              (in `make`) unchanged?

What is copied: emu/*.c and their four headers, include/emu86.h,
emu386.h, pcbios.h and pc386.h. Not types.h or keys.h, which are
HavenDOS's own and which RetroPC carries copies of.

emu/FROM-RETROPC.txt records the RetroPC version and commit, and the
SHA-256 of every copied file. --check refuses a build where one of
them has changed since. An emulator fix made here and not there would
be lost at the next sync, silently, so the place to fix it is RetroPC.
The RetroPC side refuses anything a kernel cannot link (its
tools/check_freestanding.py), so a sync cannot bring in printf.
"""
import hashlib, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STAMP = os.path.join(ROOT, "emu", "FROM-RETROPC.txt")
HEADERS = ["include/emu86.h", "include/emu386.h", "include/pcbios.h", "include/pc386.h"]


def files_in(base):
    emu = sorted("emu/" + f for f in os.listdir(os.path.join(base, "emu")) if f.endswith(".c"))
    return emu + HEADERS


def sha(p):
    return hashlib.sha256(open(p, "rb").read()).hexdigest()


def check():
    if not os.path.exists(STAMP):
        sys.exit("sync_emu: emu/FROM-RETROPC.txt is missing -- run tools/sync_emu.py <RetroPC checkout>")
    lines = [l for l in open(STAMP).read().splitlines() if l and not l.startswith("#")]
    head, rows = lines[0], lines[1:]
    listed = set()
    for r in rows:
        h, name = r.split(None, 1)
        listed.add(name)
        p = os.path.join(ROOT, name)
        if not os.path.exists(p):
            sys.exit(f"sync_emu: {name} is listed in emu/FROM-RETROPC.txt and missing")
        if sha(p) != h:
            sys.exit(f"sync_emu: {name} has changed since it came from {head}.\n"
                     f"  Retro PC's emulators are worked on in github.com/MGKFN/RetroPC: make the\n"
                     f"  change there and run tools/sync_emu.py, or it is lost at the next sync.")
    extra = sorted(set(files_in(ROOT)) - listed)
    if extra:
        sys.exit("sync_emu: not from RetroPC: " + ", ".join(extra))
    print(f"sync_emu: ok, emu/ is {head}")


def sync(src):
    vh = open(os.path.join(src, "src", "version.h")).read()
    ver = re.search(r'#define\s+RETROPC_VERSION\s+"([^"]+)"', vh).group(1)
    commit = subprocess.run(["git", "-C", src, "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip() or "unknown"
    dirty = subprocess.run(["git", "-C", src, "status", "--porcelain", "emu", "include"],
                           capture_output=True, text=True).stdout.strip()
    if dirty:
        sys.exit("sync_emu: the RetroPC checkout has uncommitted changes in emu/ or include/ -- commit them first")
    out = [f"# GENERATED by tools/sync_emu.py -- where emu/ came from. Do not edit.",
           f"RetroPC {ver} {commit}"]
    names = files_in(src)
    old = set(files_in(ROOT)) - set(names)
    for n in old:
        os.unlink(os.path.join(ROOT, n))
    for n in names:
        data = open(os.path.join(src, n), "rb").read()
        open(os.path.join(ROOT, n), "wb").write(data)
        out.append(f"{hashlib.sha256(data).hexdigest()}  {n}")
    open(STAMP, "w").write("\n".join(out) + "\n")
    print(f"sync_emu: emu/ <- RetroPC {ver} ({commit}), {len(names)} files" + (f", removed {sorted(old)}" if old else ""))


if len(sys.argv) == 2 and sys.argv[1] == "--check":
    check()
elif len(sys.argv) == 2:
    sync(sys.argv[1])
else:
    sys.exit(__doc__)
