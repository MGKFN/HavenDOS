#!/usr/bin/env python3
"""make_grub_efi_embed.py -- generate include/grub_efi_embed.h

The UEFI loader HavenDOS installs onto an EFI System Partition.

include/grub_embed.h and include/grub_disk_embed.h are both
`grub-mkimage -O i386-pc`: BIOS images, which a UEFI-only machine will not
execute. This is the third one, built `-O x86_64-efi`, and it is what makes
installing onto a modern laptop possible at all. HavenDOS has booted under
UEFI since 0.8 Beta -- from the ISO, using the loader grub-mkrescue puts on
it -- but it has never been able to INSTALL a system that boots that way,
because it had no PE32+ loader of its own to write.

Usage: make_grub_efi_embed.py <bootx64.efi> <output.h>

The module list lives in the Makefile rule that calls grub-mkimage, not
here; this only turns the result into a C array. Two modules in that list
are worth knowing about:

    chainloader   without it the generated grub.cfg cannot boot Windows,
                  and a "dual boot" that only boots HavenDOS is not one
    search_label  how the menu finds the HavenDOS partition without
                  hardcoding a disk or partition number, which would
                  break the moment the user adds a drive
"""
import os
import sys

if len(sys.argv) != 3:
    sys.exit("usage: make_grub_efi_embed.py <bootx64.efi> <output.h>")

efi_file, out_file = sys.argv[1], sys.argv[2]

with open(efi_file, "rb") as f:
    data = f.read()

if len(data) < 1024:
    sys.exit("make_grub_efi_embed: %s is only %d bytes -- that is not a loader"
             % (efi_file, len(data)))
if data[:2] != b"MZ":
    sys.exit("make_grub_efi_embed: %s does not start with MZ, so it is not a\n"
             "  PE32+ image and no firmware will execute it. Was it built\n"
             "  with -O x86_64-efi?" % efi_file)

lines = [
    "#ifndef GRUB_EFI_EMBED_H",
    "#define GRUB_EFI_EMBED_H",
    '#include "types.h"',
    "",
    "/* GENERATED by tools/make_grub_efi_embed.py -- do not edit.",
    " *",
    " * The UEFI loader, as a PE32+ image, written to the EFI System",
    " * Partition at install time. Built from %s (%d bytes)." % (
        os.path.basename(efi_file), len(data)),
    " */",
    "static const uint8_t grub_efi_img[] = {",
]
for i in range(0, len(data), 16):
    lines.append("    " + ", ".join("0x%02X" % b for b in data[i:i + 16]) + ",")
lines.append("};")
lines.append("static const uint32_t grub_efi_img_size = %d;" % len(data))
lines.append("")
lines.append("#endif /* GRUB_EFI_EMBED_H */")

with open(out_file, "w") as f:
    f.write("\n".join(lines) + "\n")

print("make_grub_efi_embed: %s -> %s  (%d bytes, PE32+)"
      % (efi_file, out_file, len(data)))
