#!/usr/bin/env python3
"""make_isodir.py -- create the ISO skeleton if it is not there.

WHY THIS EXISTS

The source archive shipped with v0.8.3.1 does not contain isodir/. The
kernel builds, every suite passes, all five build checks pass -- and then
`make` dies at the ISO step with

    FileNotFoundError: 'isodir/version.txt'

because isodir/boot/grub/grub.cfg is a source file that never got into the
zip. Anyone building from the archive in an empty directory hits it, which
is exactly the standing requirement 1.0 is supposed to meet.

WHAT IT WILL AND WILL NOT DO

It creates ONLY what is missing, and it NEVER edits or replaces a file
that is already there. If you have a real isodir/ -- with your theme, your
menu, your wording -- this does nothing at all and says so. It is a
fallback for a tree that has none, not a generator that owns the file.

WHERE THE MENU COMES FROM

Not invented. The entries are derived from kernel/main.c's own command
line parser, which is the only thing that decides what a boot option does:

    mode=shell  mode=safe  mode=lowres  mode=desktop
    install=1              gfx=text     quiet

and from the order the test harnesses count on, which is written down in
them:

    harness/fat32_boot.py     SHELL_MODE_INDEX = 1
    harness/uefi_dualboot.py  MENU_INSTALL     = 3
    harness/fat16_regress.py  "Install to Disk" is the fourth entry

So: 0 normal, 1 shell, 2 safe, 3 install. A generated menu that disagreed
with those three harnesses would be found by them immediately, which is
the only reason it is safe to generate at all.

The version in the titles is left as a placeholder; tools/make_version.py
rewrites it from include/version.h on every build, as it does for a real
isodir.
"""
import os
import sys

MENU = """\
# GENERATED by tools/make_isodir.py because this tree had no isodir/.
#
# The entries and their ORDER are not arbitrary. kernel/main.c's
# apply_cmdline() defines what each argument does, and three harnesses
# count on the order:
#
#   index 0  normal boot
#   index 1  shell mode      harness/fat32_boot.py SHELL_MODE_INDEX = 1
#   index 2  safe mode
#   index 3  install         harness/uefi_dualboot.py MENU_INSTALL = 3
#
# Replace this file with your own and this script will leave it alone.

# HavenDOS renders through a framebuffer console, and it gets that
# framebuffer from the mode GRUB sets before handing over -- Multiboot1
# VBE fields, which is why gfxpayload=keep matters here and not just for
# GRUB's own menu. Without all_video loaded and a gfxmode it can actually
# satisfy, GRUB stops at
#
#     error: no suitable video mode found.
#
# which is what a generated menu with no video setup in it does under
# OVMF. Found by booting one.
insmod all_video
insmod gfxterm
# v0.8.8.6: the native modes of a modern laptop panel come first.
# Kyan's HP landed on 1024x768 because the list started at 1280x800,
# which his GPU does not offer -- and 1024x768 at a readable cell is
# 64x24, SMALLER than the 80x25 every app lays out for, which is
# where "some apps still go off the screen" came from. The console
# refuses to go below 80x25 now whatever mode it is given, but a
# bigger framebuffer is a better starting point than a rescued one.
#
# GRUB walks this list and takes the first the hardware offers, so
# adding modes to the front costs nothing on a machine that cannot do
# them. 640x480 stays last: it is the one every VGA can do, and the
# fallback must not be removed to make room.
set gfxmode=1920x1080,1600x900,1440x900,1366x768,1280x800,1024x768,800x600,640x480,auto
set gfxpayload=keep
terminal_output gfxterm

# The timeout has to outlast the harnesses. They sleep through OVMF's
# slow start before touching the menu -- harness/uefi_dualboot.py waits 12
# seconds, harness/esp_update.py waits 26 -- and a menu that has already
# counted down and booted the default by then cannot be driven at all.
# Found by running uefi_dualboot.py against a generated isodir with
# timeout=10: every installer check failed because the install never
# started.
set timeout=60
set default=0

menuentry "HavenDOS v0.0.0" {
    multiboot /boot/havendos.elf mode=desktop gfx=text live
    boot
}

menuentry "HavenDOS v0.0.0 -- Shell Mode" {
    multiboot /boot/havendos.elf mode=shell gfx=text live
    boot
}

menuentry "HavenDOS v0.0.0 -- Safe Mode" {
    multiboot /boot/havendos.elf mode=safe gfx=text live
    boot
}

# ── `live` and `install=1` are mutually exclusive (v0.8.5.4) ─────────
#
# Every install entry used to pass `live`, and `live` makes the installer
# REFUSE to write: fs/install.c returns INSTADD_E_LIVE (-12) and
# havendos_install_additive() returns the same, both with the message
# "a live session can preview but not write -- boot the 'Install to Disk'
# entry". Which was the entry the person had just booted.
#
# So the ISO could not install, from any entry, and the one screen that
# could have explained it was pointing at itself. Found on a real laptop
# after typing YES on the confirmation.
#
# `live` is right for the entries that only look around -- desktop, shell,
# safe mode -- because it means no disk is probed and nothing is mounted,
# which is what you want from install media you may be running on
# somebody else's machine. It is wrong for anything that writes.
menuentry "HavenDOS v0.0.0 -- Install to Disk" {
    multiboot /boot/havendos.elf install=1 gfx=text
    boot
}

# Entry 4, AFTER the four the harnesses index, so their counting is
# unaffected. This one deliberately does NOT pass `live`.
#
# `live` means what kernel/main.c says it means: no disk probed, no disk
# mounted, RAM only. That is right for an install medium and wrong for
# this job, because `update` begins by requiring fat16_detected() -- it
# writes the new kernel to the HavenDOS partition that is already on the
# disk. A live shell cannot see that partition and refuses with "No FAT16
# partition found".
#
# So: boot this, type `update`, and the kernel staged on the EFI System
# Partition replaces /boot/havendos.elf in place. Nothing is
# repartitioned, the GPT is not touched, and the firmware boot entry that
# is already there keeps working.
menuentry "HavenDOS v0.0.0 -- Update installed system from the ESP" {
    multiboot /boot/havendos.elf mode=shell gfx=text
    boot
}
"""


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "isodir"
    cfg = os.path.join(root, "boot", "grub", "grub.cfg")

    made = []
    for d in (root, os.path.join(root, "boot"),
              os.path.join(root, "boot", "grub")):
        if not os.path.isdir(d):
            os.makedirs(d, exist_ok=True)
            made.append(d + "/")

    if os.path.exists(cfg):
        if made:
            print("make_isodir: created %s (grub.cfg was already there)"
                  % ", ".join(made))
        else:
            print("make_isodir: isodir/ is already complete, nothing to do")
        return 0

    with open(cfg, "w", encoding="ascii", newline="\n") as f:
        f.write(MENU)
    made.append(cfg)
    print("make_isodir: created %s" % ", ".join(made))
    print("make_isodir: the menu is a RECONSTRUCTION from kernel/main.c's")
    print("             command line parser and the harness indices.")
    print("             Replace isodir/boot/grub/grub.cfg with your own and")
    print("             this script will never touch it again.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
