#!/usr/bin/env python3
"""make_retro_images.py -- the archive's old builds, into the kernel.  v0.9.7.

Reads archive/retro/IMAGES.txt and writes include/retro_images.h: each
listed image as a byte array, with its id, title and a line about it,
for shell/retro.c and tests/test_emu86.c -- the same bytes in both, so
the suite tests what ships.

Refuses (exit 1) if a listed file is missing, if its SHA-256 is not the
one recorded, or if an id would not make an 8.3 file name.
"""
import hashlib, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ARCH = os.path.join(ROOT, "archive", "retro")

def die(msg):
    sys.exit("make_retro_images: " + msg)

def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "include", "retro_images.h")
    rows = []
    for ln in open(os.path.join(ARCH, "IMAGES.txt"), encoding="utf-8"):
        ln = ln.strip()
        if not ln or ln.startswith("#"): continue
        parts = [p.strip() for p in ln.split("|")]
        if len(parts) not in (5, 6): die("bad line: " + ln)
        ident, title, fn, sha, about = parts[:5]
        kind = parts[5] if len(parts) == 6 else "floppy"
        cfg = b""
        if kind.startswith("multiboot:"):
            cp = os.path.join(ARCH, kind.split(":", 1)[1])
            if not os.path.exists(cp): die(f"{kind} is listed but not in archive/retro")
            cfg = open(cp, "rb").read()
        elif kind != "floppy":
            die(f"kind {kind!r}: floppy or multiboot:<file.cfg>")
        if not re.fullmatch(r"[A-Z0-9]{1,8}", ident):
            die(f"id {ident!r} must be 1-8 capital letters or digits (it names RETRO/{ident}.HDD)")
        p = os.path.join(ARCH, fn)
        if not os.path.exists(p): die(f"{fn} is listed but not in archive/retro")
        data = open(p, "rb").read()
        got = hashlib.sha256(data).hexdigest()
        if got != sha.lower():
            die(f"{fn} hashes to {got}, not the {sha} recorded -- the archive copy has changed")
        if kind == "floppy" and (len(data) < 512 or data[510:512] != b"\x55\xaa"):
            die(f"{fn} has no boot signature at offset 510")
        if kind != "floppy" and data[:4] != b"\x7fELF":
            die(f"{fn} is listed as a Multiboot kernel and is not an ELF file")
        rows.append((ident, title, about, data, kind != "floppy", cfg))

    L = ["/* include/retro_images.h -- GENERATED by tools/make_retro_images.py",
         "   from archive/retro/IMAGES.txt. Do not edit; edit the manifest. */",
         "#pragma once", "#include \"types.h\"", "",
         "typedef struct {",
         "    const char    *id, *title, *about;",
         "    const uint8_t *data;",
         "    uint32_t       size;",
         "    int            multiboot;   /* 0 a boot floppy, 1 a 32-bit kernel (v0.9.7.2) */",
         "    const char    *cfg;         /* its grub.cfg, when multiboot */",
         "    uint32_t       cfg_size;",
         "} retro_image_t;", ""]
    for i, (ident, title, about, data, mb, cfg) in enumerate(rows):
        L.append(f"static const uint8_t retro_img_{i}[{len(data)}] = {{")
        for k in range(0, len(data), 16):
            L.append("    " + ",".join(f"0x{b:02X}" for b in data[k:k+16]) + ",")
        L.append("};")
    L.append("")
    L.append("static const retro_image_t retro_images[] = {")
    for i, (ident, title, about, data, mb, cfg) in enumerate(rows):
        # the cfg as one C string: ASCII only (its comments draw lines with
        # box characters, which no menu shows), CRs dropped
        txt = "".join(ch if 32 <= ord(ch) < 127 or ch == "\n" else ("-" if ord(ch) > 127 else "")
                      for ch in cfg.decode("utf-8", "replace")) if mb else ""
        cs = '"' + txt.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"' if mb else "0"
        L.append(f"    {{ {c_str(ident)}, {c_str(title)}, {c_str(about)}, retro_img_{i}, {len(data)}u, {1 if mb else 0}, {cs}, {len(txt)}u }},")
    L.append("};")
    L.append(f"#define RETRO_NIMAGES {len(rows)}")
    tmp = out + ".tmp"
    open(tmp, "w").write("\n".join(L) + "\n")
    os.replace(tmp, out)
    print(f"make_retro_images: {len(rows)} image(s) -> {os.path.relpath(out, ROOT)}")

main()
