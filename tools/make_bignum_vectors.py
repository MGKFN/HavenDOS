#!/usr/bin/env python3
"""make_bignum_vectors.py -- the numbers tests/test_bignum.c checks against.

WHY THE VECTORS ARE GENERATED AND NOT TYPED

A bignum is the one kind of code where a suite written by the person
who wrote the implementation is worth almost nothing: both sides are
the same arithmetic, and a carry handled wrongly in one is handled
wrongly in the other. tests/test_usbmux.c passed 79 of 79 against a
header the phone has never used, for exactly that reason, and this is
that hazard in its purest form.

So every expected value here comes from somewhere else:

  PYTHON'S INTEGERS, which are an independent arbitrary-precision
  implementation nobody in this project wrote.

  OPENSSL, for the RSA key material. The key is generated by
  `openssl genrsa`, so n, e, d, p and q are a real key produced by the
  library the rest of the world uses -- not three primes this script
  multiplied together. Python then computes the expected
  ciphertexts and plaintexts from it.

A match therefore means the kernel's arithmetic agrees with CPython
and with OpenSSL. It is still possible for all three to be wrong in
the same way, and that is not a risk worth more effort than this.

WHAT IS COVERED, AND WHY EACH ONE IS HERE

  the carry cases      0xFFFFFFFF + 1 and friends: the limb boundary,
                       where an addition that forgets to carry and one
                       that carries twice both produce plausible
                       numbers
  squaring             bn_mul(&x,&x,&x) is the first thing anybody
                       writes and accumulating into the destination
                       while reading it is wrong in a way that gives
                       ALMOST the right answer
  division by a number bigger than the dividend, by 1, by itself
  modexp               including e=65537 and a full 2048-bit private
                       exponent, which is the operation the old
                       byte-wise code took 18 seconds over
  the modular inverse  d*e mod phi == 1 for a real key, which is the
                       property RSA actually rests on
  RSA round trip       m -> m^e mod n -> ^d mod n -> m, with the
                       numbers from OpenSSL's own key

    python3 tools/make_bignum_vectors.py tests
"""
import os
import random
import subprocess
import sys


def sh(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("make_bignum_vectors: %s failed:\n%s"
                 % (" ".join(cmd), r.stderr))
    return r.stdout


def need(tool):
    if subprocess.run(["sh", "-c", "command -v " + tool],
                      capture_output=True).returncode != 0:
        sys.exit("make_bignum_vectors: %s is not installed" % tool)


def hx(v, minbytes=1):
    """A big integer as a C byte array initialiser, big-endian."""
    if v == 0:
        return "{ 0 }", 1
    b = v.to_bytes(max(minbytes, (v.bit_length() + 7) // 8), "big")
    return "{ " + ",".join("0x%02x" % x for x in b) + " }", len(b)


def parse_rsa(pem_path, bits):
    out = sh(["openssl", "rsa", "-in", pem_path, "-text", "-noout"])
    # openssl prints the components as colon-separated hex across lines
    fields = {}
    key = None
    buf = []
    labels = {
        "modulus": "n", "privateExponent": "d",
        "prime1": "p", "prime2": "q",
        "publicExponent": "e",
    }
    for line in out.splitlines():
        s = line.strip()
        head = s.split(":")[0]
        if head in labels:
            if key:
                fields[key] = buf
            key = labels[head]
            buf = []
            if head == "publicExponent":
                # printed as "publicExponent: 65537 (0x10001)"
                fields["e"] = [s.split()[1]]
                key = None
            continue
        if key is not None:
            if s and all(c in "0123456789abcdef:" for c in s):
                buf.append(s)
            else:
                fields[key] = buf
                key = None
                buf = []
    if key:
        fields[key] = buf

    def val(name):
        if name == "e":
            return int(fields["e"][0])
        h = "".join(fields[name]).replace(":", "")
        return int(h, 16)

    n, e, d, p, q = val("n"), val("e"), val("d"), val("p"), val("q")
    if p * q != n:
        sys.exit("make_bignum_vectors: openssl's p*q is not n -- the "
                 "parse is wrong, and a wrong key would make every "
                 "check below meaningless")
    if n.bit_length() != bits:
        sys.exit("make_bignum_vectors: expected a %d-bit modulus, got %d"
                 % (bits, n.bit_length()))
    return n, e, d, p, q


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "tests"
    rng = random.Random(0x8E71053)          # reproducible, not secret

    a = []
    w = a.append
    w("/* GENERATED by tools/make_bignum_vectors.py -- do not edit.")
    w("")
    w("   Every expected value below came from CPython's integers or")
    w("   from OpenSSL, not from net/bignum.c. A bignum suite written")
    w("   by whoever wrote the bignum is worth almost nothing: both")
    w("   sides are the same arithmetic and a carry handled wrongly in")
    w("   one is handled wrongly in the other. */")
    w("")
    w("typedef struct {")
    w("    const char          *what;")
    w("    const unsigned char *a; unsigned a_len;")
    w("    const unsigned char *b; unsigned b_len;")
    w("    const unsigned char *r; unsigned r_len;")
    w("} bnvec_t;")
    w("")

    def emit_set(name, cases, note):
        """cases: list of (what, a, b, expected)"""
        w("/* %s */" % note)
        for i, (what, x, y, r) in enumerate(cases):
            for tag, v in (("a", x), ("b", y), ("r", r)):
                s, n = hx(v)
                w("static const unsigned char %s_%d%s[] = %s;"
                  % (name, i, tag, s))
        w("static const bnvec_t %s[] = {" % name)
        for i, (what, x, y, r) in enumerate(cases):
            w('    { "%s", %s_%da, sizeof %s_%da, %s_%db, sizeof %s_%db,'
              ' %s_%dr, sizeof %s_%dr },'
              % (what, name, i, name, i, name, i, name, i,
                 name, i, name, i))
        w("};")
        w("#define %s_N ((int)(sizeof(%s)/sizeof(%s[0])))"
          % (name.upper(), name, name))
        w("")

    # ── carries, boundaries, and the cases that look plausible when
    #    they are wrong ────────────────────────────────────────────
    M32 = (1 << 32) - 1
    adds = [
        ("0 + 0", 0, 0),
        ("1 + 0", 1, 0),
        ("the limb boundary", M32, 1),
        ("carry through two limbs", (1 << 64) - 1, 1),
        ("carry through eight limbs", (1 << 256) - 1, 1),
        ("two 2048-bit numbers", rng.getrandbits(2048),
         rng.getrandbits(2048)),
        ("a big one and a small one", rng.getrandbits(2048), 1),
    ]
    emit_set("BN_ADD", [(w0, x, y, x + y) for w0, x, y in adds],
             "addition, and every place a carry can be lost or doubled")

    subs = [
        ("0 - 0", 0, 0),
        ("the limb boundary", 1 << 32, 1),
        ("a borrow through eight limbs", 1 << 256, 1),
        ("equal values", 12345678901234567890, 12345678901234567890),
        ("two 2048-bit numbers", 0, 0),
    ]
    big1 = rng.getrandbits(2048)
    big2 = rng.getrandbits(2000)
    subs[-1] = ("two 2048-bit numbers", max(big1, big2), min(big1, big2))
    emit_set("BN_SUB", [(w0, x, y, x - y) for w0, x, y in subs],
             "subtraction, including the borrow chains")

    muls = [
        ("0 * anything", 0, rng.getrandbits(512)),
        ("1 * anything", 1, rng.getrandbits(512)),
        ("the limb boundary squared", M32, M32),
        ("two 64-bit numbers", rng.getrandbits(64), rng.getrandbits(64)),
        ("two 1024-bit numbers", rng.getrandbits(1024),
         rng.getrandbits(1024)),
    ]
    emit_set("BN_MUL", [(w0, x, y, x * y) for w0, x, y in muls],
             "multiplication")

    # Squaring gets its own set: bn_mul(&x,&x,&x) is the aliasing case.
    sqs = [(("%d bits squared" % b), v, v, v * v)
           for b, v in ((32, M32), (64, rng.getrandbits(64)),
                        (512, rng.getrandbits(512)),
                        (1024, rng.getrandbits(1024)))]
    emit_set("BN_SQ", sqs, "squaring, which is the aliasing case")

    divs = []
    for what, x, y in [
        ("divisor bigger than dividend", 7, 1000003),
        ("divide by one", rng.getrandbits(512), 1),
        ("divide by itself", 0, 0),
        ("exact multiple", 0, 0),
        ("2048 bits by 1024", rng.getrandbits(2048),
         rng.getrandbits(1024) | 1),
        ("1024 bits by a small number", rng.getrandbits(1024), 65537),
    ]:
        divs.append((what, x, y))
    v = rng.getrandbits(777) | 1
    divs[2] = ("divide by itself", v, v)
    q0 = rng.getrandbits(400) | 1
    divs[3] = ("exact multiple", q0 * 123456791, 123456791)
    emit_set("BN_DIV", [(w0, x, y, x // y) for w0, x, y in divs],
             "division: the quotient")
    emit_set("BN_REM", [(w0, x, y, x % y) for w0, x, y in divs],
             "division: the remainder, from the same cases")

    # ── modexp ──────────────────────────────────────────────────────
    w("/* modexp: base, exponent, modulus, expected. The moduli are")
    w("   odd, because Montgomery needs an odd modulus and every RSA")
    w("   modulus is a product of two odd primes. */")
    w("typedef struct {")
    w("    const char          *what;")
    w("    const unsigned char *b; unsigned b_len;")
    w("    const unsigned char *e; unsigned e_len;")
    w("    const unsigned char *m; unsigned m_len;")
    w("    const unsigned char *r; unsigned r_len;")
    w("} bnexp_t;")
    exps = [
        ("tiny", 4, 13, 497),
        ("exponent 0", rng.getrandbits(256), 0, rng.getrandbits(256) | 1),
        ("exponent 1", rng.getrandbits(256), 1, rng.getrandbits(256) | 1),
        ("modulus 1", rng.getrandbits(256), 65537, 1),
        ("base larger than the modulus", rng.getrandbits(600),
         65537, rng.getrandbits(256) | 1),
        ("256-bit modulus, e=65537", rng.getrandbits(256), 65537,
         rng.getrandbits(256) | 1),
        ("1024-bit modulus, e=65537", rng.getrandbits(1024), 65537,
         rng.getrandbits(1024) | 1),
    ]
    for i, (what, b, e, m) in enumerate(exps):
        r = pow(b, e, m)
        for tag, v in (("b", b), ("e", e), ("m", m), ("r", r)):
            s, _ = hx(v)
            w("static const unsigned char BN_EXP_%d%s[] = %s;"
              % (i, tag, s))
    w("static const bnexp_t BN_EXP[] = {")
    for i, (what, b, e, m) in enumerate(exps):
        w('    { "%s", BN_EXP_%db, sizeof BN_EXP_%db, BN_EXP_%de,'
          ' sizeof BN_EXP_%de, BN_EXP_%dm, sizeof BN_EXP_%dm,'
          ' BN_EXP_%dr, sizeof BN_EXP_%dr },'
          % (what, i, i, i, i, i, i, i, i))
    w("};")
    w("#define BN_EXP_N ((int)(sizeof(BN_EXP)/sizeof(BN_EXP[0])))")
    w("")

    # ── the modular inverse ─────────────────────────────────────────
    w("/* modular inverses, and two values that have none. */")
    w("typedef struct {")
    w("    const char          *what;")
    w("    const unsigned char *a; unsigned a_len;")
    w("    const unsigned char *m; unsigned m_len;")
    w("    const unsigned char *r; unsigned r_len;   /* 0 len = none */")
    w("    int                  exists;")
    w("} bninv_t;")
    invs = []
    invs.append(("3 mod 11", 3, 11))
    invs.append(("65537 mod a 512-bit odd number", 65537,
                 rng.getrandbits(512) | 1))
    invs.append(("a 256-bit value mod a 512-bit odd number",
                 rng.getrandbits(256) | 1, rng.getrandbits(512) | 1))
    invs.append(("no inverse: a shares a factor", 6, 9))
    # ── EVEN MODULI, which every vector above excluded ──────────────
    #
    # The first version of this generator wrote `| 1` on every modulus
    # and the suite went green on a bn_modinv that REFUSED an even
    # modulus by design. That was the fixture being looser than the
    # device: RSA's d = e^-1 mod lcm(p-1, q-1), and the lcm of two
    # even numbers is always even, so the only inverse the kernel
    # actually needs was the one no vector asked for.
    invs.append(("3 mod 20, an even modulus", 3, 20))
    invs.append(("65537 mod an even 512-bit number", 65537,
                 rng.getrandbits(512) & ~1))
    invs.append(("no inverse: even a, even m", 4, 10))
    # modulus 1, where the inverse is 0 and not "none" -- bn_modexp
    # special-cases m == 1 and the two must agree.
    invs.append(("modulus 1", 7, 1))
    rows = []
    n_even_ok = 0
    for what, x, m in invs:
        try:
            r = pow(x, -1, m)
            ok = 1
        except ValueError:
            r = 0
            ok = 0
        if ok and m % 2 == 0 and m != 0:
            n_even_ok += 1
        rows.append((what, x, m, r, ok))
    if n_even_ok == 0:
        sys.exit("make_bignum_vectors: no vector has an invertible "
                 "value modulo an EVEN modulus -- which is the only "
                 "kind RSA needs, and a suite without one passed a "
                 "bn_modinv that refused them all")
    for i, (what, x, m, r, ok) in enumerate(rows):
        for tag, v in (("a", x), ("m", m), ("r", r)):
            s, _ = hx(v)
            w("static const unsigned char BN_INV_%d%s[] = %s;"
              % (i, tag, s))
    w("static const bninv_t BN_INV[] = {")
    for i, (what, x, m, r, ok) in enumerate(rows):
        w('    { "%s", BN_INV_%da, sizeof BN_INV_%da, BN_INV_%dm,'
          ' sizeof BN_INV_%dm, BN_INV_%dr, sizeof BN_INV_%dr, %d },'
          % (what, i, i, i, i, i, i, ok))
    w("};")
    w("#define BN_INV_N ((int)(sizeof(BN_INV)/sizeof(BN_INV[0])))")
    w("")

    # ── a real RSA key, from OpenSSL ────────────────────────────────
    need("openssl")
    pem = os.path.join(out_dir, "bnkey.pem")
    sh(["openssl", "genrsa", "-out", pem, "2048"])
    n, e, d, p, q = parse_rsa(pem, 2048)
    os.unlink(pem)
    def gcd(x, y):
        while y:
            x, y = y, x % y
        return x

    phi = (p - 1) * (q - 1)
    lam = phi // gcd(p - 1, q - 1)       # lcm(p-1, q-1)
    msg = rng.getrandbits(2000)
    ct = pow(msg, e, n)
    pt = pow(ct, d, n)
    assert pt == msg
    assert p * q == n

    # OPENSSL'S d IS NOT e^-1 mod phi.
    #
    # This script asserted that first and openssl failed it, which is
    # the generator earning its keep: RFC 8017 defines d against
    # lambda(n) = lcm(p-1, q-1), and openssl follows the RFC. phi is a
    # MULTIPLE of lambda, so e^-1 mod phi is also a working private
    # exponent -- textbook RSA uses it and decryption succeeds either
    # way -- but it is a DIFFERENT NUMBER from the one in the key file.
    #
    # So the suite checks bn_modinv against lambda. Had this script
    # quietly used phi, the inverse check would have failed against a
    # perfectly correct bn_modinv and the time would have gone into
    # hunting a bug in the extended Euclid.
    if (d * e) % lam != 1:
        sys.exit("make_bignum_vectors: openssl's d is not e^-1 mod "
                 "lambda either -- the key parse is wrong")
    assert (d * e) % phi != 1 or lam == phi   # the point above, held

    w("/* A REAL RSA-2048 KEY, from `openssl genrsa`. Not three primes")
    w("   this script multiplied together: the point is that the")
    w("   kernel's arithmetic agrees with the library everybody else")
    w("   uses, on a key that library produced.")
    w("")
    w("   BN_RSA_lam IS THE ONE TO CHECK bn_modinv AGAINST. openssl")
    w("   follows RFC 8017 and computes d = e^-1 mod lcm(p-1,q-1), not")
    w("   mod (p-1)(q-1). Both are working private exponents and both")
    w("   decrypt, but they are different numbers, and the generator")
    w("   caught this by asserting the wrong one first. */")
    for tag, v in (("n", n), ("e", e), ("d", d), ("p", p), ("q", q),
                   ("phi", phi), ("lam", lam), ("msg", msg), ("ct", ct)):
        s, _ = hx(v)
        w("static const unsigned char BN_RSA_%s[] = %s;" % (tag, s))
    w("")
    w("#define BN_RSA_BITS 2048")
    w("")

    path = os.path.join(out_dir, "bignum_vectors.inc")
    open(path, "w", encoding="utf-8").write("\n".join(a) + "\n")
    print("make_bignum_vectors: %s" % path)
    print("  %d add, %d sub, %d mul, %d square, %d div/rem, %d modexp, "
          "%d inverse" % (len(adds), len(subs), len(muls), len(sqs),
                          len(divs), len(exps), len(rows)))
    print("  plus a real RSA-2048 key from openssl genrsa")
    return 0


if __name__ == "__main__":
    sys.exit(main())
