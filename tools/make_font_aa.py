#!/usr/bin/env python3
"""
tools/make_font_aa.py -- the smooth console font. v0.9.7.10.

Kyan, 24 Nov: complaints that HavenDOS "is still text mode and outdated
in 2026". It has drawn its own pixels since 0.8 -- what looked old was the
font: an 8x16 bitmap blown up 2x or 3x, every letter a stack of squares.

This makes a MASTER: every glyph drawn at 32x64 with smooth (anti-aliased)
edges, 16 levels of coverage per pixel. drivers/vga.c shrinks it to the
console's actual cell size at boot -- 16x32 at 80x25 on 1280x800, 24x48 on
a 1920x1200 panel, 21x42 for an app full screen on 1920x1080 -- and blends
each pixel between the text and background colours. So the same master is
sharp at every size, instead of one bitmap scaled by whole numbers.

  ASCII and the accented letters (0x80-0xA5): IBM Plex Mono Medium -- the
      THS technical face, the one on the website and in the manuals. SIL
      Open Font License 1.1 (via @fontsource/ibm-plex-mono).
  Everything else: include/font8x16.h's own glyph, enlarged 4x with no
      smoothing, so anything that relies on a cell's exact pixels (block
      and line characters, should the UI ever use them) still meets its
      neighbours edge to edge.

Outputs, both committed:
  include/font_aa.h     the master, 4 bits a pixel, for the kernel
  harness/font_aa.bin   the same bytes, for harness/fbtext.py to read the
                        screen back with

    python3 tools/make_font_aa.py
"""
import os
import re
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_H = os.path.join(ROOT, "include", "font_aa.h")
OUT_BIN = os.path.join(ROOT, "harness", "font_aa.bin")
W, H = 32, 64

PLEX = os.path.expanduser("~/.local/share/fonts/ibm-plex-mono-latin-500-normal.ttf")
SIZE = 46          # Plex's advance is 0.6 em: 27.6 px of a 32 px cell
BASELINE = 46      # cap height 0.698 em = 32 px; descender ends near 56


def bitmap_glyphs():
    """font8x16[] out of include/font8x16.h."""
    src = open(os.path.join(ROOT, "include", "font8x16.h")).read()
    body = src[src.index("font8x16[FONT8X16_GLYPHS*FONT8X16_HEIGHT]"):]
    body = body[body.index("{") + 1:body.index("};")]
    vals = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]{2})", body)]
    if len(vals) != 256 * 16:
        sys.exit("make_font_aa: font8x16 has %d bytes, not 4096" % len(vals))
    return vals


def from_bitmap(bm, code):
    im = Image.new("L", (W, H), 0)
    px = im.load()
    for row in range(16):
        bits = bm[code * 16 + row]
        for col in range(8):
            if bits & (0x80 >> col):
                for y in range(row * 4, row * 4 + 4):
                    for x in range(col * 4, col * 4 + 4):
                        px[x, y] = 255
    return im


def from_plex(font, ch):
    im = Image.new("L", (W, H), 0)
    d = ImageDraw.Draw(im)
    adv = font.getlength(ch)
    d.text(((W - adv) / 2.0, BASELINE), ch, font=font, fill=255, anchor="ls")
    return im


def main():
    if not os.path.exists(PLEX):
        sys.exit("make_font_aa: no %s -- install @fontsource/ibm-plex-mono as TTF" % PLEX)
    bm = bitmap_glyphs()
    font = ImageFont.truetype(PLEX, SIZE)
    smooth = set(range(0x21, 0x7F)) | set(range(0x80, 0xA6))
    master = bytearray()
    for code in range(256):
        if code in smooth:
            ch = bytes([code]).decode("cp437")
            im = from_plex(font, ch)
            if not im.getbbox():                 # Plex has no such glyph
                im = from_bitmap(bm, code)
        else:
            im = from_bitmap(bm, code)
        a = im.tobytes()
        # 16 levels, rounded; a light gamma lift so thin strokes on a dark
        # background do not look starved (coverage 0.5 -> about 0.57).
        for i in range(0, W * H, 2):
            def q(v):
                v = (v / 255.0) ** 0.8
                return min(15, int(v * 15 + 0.5))
            master.append((q(a[i]) << 4) | q(a[i + 1]))

    with open(OUT_BIN, "wb") as f:
        f.write(master)
    with open(OUT_H, "w") as h:
        h.write("/* GENERATED by tools/make_font_aa.py -- do not edit.\n"
                " * The smooth console font's master: 256 glyphs of %dx%d, 4 bits a pixel,\n"
                " * two pixels a byte, high nibble first. drivers/vga.c shrinks it to the\n"
                " * cell size. ASCII and 0x80-0xA5 are IBM Plex Mono Medium (SIL Open Font\n"
                " * License 1.1); the rest is font8x16.h enlarged. */\n" % (W, H))
        h.write("#ifndef FONT_AA_H\n#define FONT_AA_H\n")
        h.write("#define FONT_AA_W %d\n#define FONT_AA_H_PX %d\n" % (W, H))
        h.write("static const unsigned char font_aa[%d] = {\n" % len(master))
        for i in range(0, len(master), 24):
            h.write("  " + ",".join("0x%02x" % b for b in master[i:i + 24]) + ",\n")
        h.write("};\n#endif\n")
    print("make_font_aa: %d bytes, %d smooth glyphs" % (len(master), len(smooth)))


if __name__ == "__main__":
    sys.exit(main())
