#!/usr/bin/env python3
"""make_retropc_res.py -- RetroPC.exe's icon and version.  v0.9.7.5.

Writes <out>/retropc.ico and <out>/retropc.rc. The .rc names the icon
and carries a VERSIONINFO read from include/version.h, so Explorer's
Properties > Details shows the HavenDOS version the program came with,
and it cannot disagree with the one `RetroPC --version` prints.

The icon is a 16x16 drawing, below, written out at 16, 32 and 48
pixels as 32-bit BMPs inside the .ico -- by hand, with struct, so the
build needs no imaging library.
"""
import os, re, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# a beige PC monitor of about 1990: blue screen, a prompt, a cursor,
# and the oxide red of the THS manuals as its power light
ART = [
    "................",
    ".oooooooooooooo.",
    ".occcccccccccco.",
    ".ocbbbbbbbbbbco.",
    ".ocbwwbwwwbbbco.",
    ".ocbbbbbbbbbbco.",
    ".ocbyyybyybbbco.",
    ".ocbbbbbbbbbbco.",
    ".ocbwbbbbbbbbco.",
    ".ocbbbbbbbbbbco.",
    ".occcccccccccco.",
    ".occcccccccrcco.",
    ".oooooooooooooo.",
    ".....oggggo.....",
    "...oooooooooo...",
    "................",
]
COL = {
    ".": None,
    "o": (0x3A, 0x34, 0x28),
    "c": (0xD8, 0xCC, 0xA8),
    "g": (0xA8, 0x9C, 0x78),
    "b": (0x00, 0x00, 0xAA),
    "w": (0xFF, 0xFF, 0xFF),
    "y": (0x55, 0xFF, 0xFF),
    "r": (0xA8, 0x32, 0x1C),
}


def bmp(scale):
    n = 16 * scale
    px = bytearray()
    for y in range(n - 1, -1, -1):                # bottom-up
        row = ART[y // scale]
        for x in range(n):
            c = COL[row[x // scale]]
            px += bytes((0, 0, 0, 0)) if c is None else bytes((c[2], c[1], c[0], 255))
    mask = bytes(((n + 31) // 32) * 4 * n)        # alpha does the work; AND mask all 0
    hdr = struct.pack("<IiiHHIIiiII", 40, n, 2 * n, 1, 32, 0, len(px) + len(mask), 0, 0, 0, 0)
    return n, hdr + px + mask


def ico():
    imgs = [bmp(s) for s in (1, 2, 3)]
    out = struct.pack("<HHH", 0, 1, len(imgs))
    off = 6 + 16 * len(imgs)
    for n, data in imgs:
        out += struct.pack("<BBBBHHII", n % 256, n % 256, 0, 0, 1, 32, len(data), off)
        off += len(data)
    for _, data in imgs:
        out += data
    return out


def version():
    h = open(os.path.join(ROOT, "include", "version.h")).read()
    get = lambda k: int(re.search(r"#define\s+HAVENDOS_VER_" + k + r"\s+(\d+)", h).group(1))
    num = re.search(r'#define\s+HAVENDOS_VER_NUM\s+"([^"]+)"', h).group(1)
    return (get("MAJOR"), get("MINOR"), get("PATCH"), get("BUILD")), num


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "dist", "retropc", "res")
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "retropc.ico"), "wb").write(ico())
    (a, b, c, d), num = version()
    rc = f'''// GENERATED by tools/make_retropc_res.py -- do not edit
1 ICON "retropc.ico"
1 VERSIONINFO
FILEVERSION {a},{b},{c},{d}
PRODUCTVERSION {a},{b},{c},{d}
FILEOS 0x40004
FILETYPE 0x1
BEGIN
  BLOCK "StringFileInfo"
  BEGIN
    BLOCK "040904B0"
    BEGIN
      VALUE "CompanyName", "Tech Haven Studios"
      VALUE "FileDescription", "Retro PC -- the old builds on emulated PCs"
      VALUE "FileVersion", "{num}"
      VALUE "InternalName", "RetroPC"
      VALUE "LegalCopyright", "Tech Haven Studios"
      VALUE "OriginalFilename", "RetroPC.exe"
      VALUE "ProductName", "Retro PC (HavenDOS {num})"
      VALUE "ProductVersion", "{num}"
    END
  END
  BLOCK "VarFileInfo"
  BEGIN
    VALUE "Translation", 0x409, 1200
  END
END
'''
    open(os.path.join(out, "retropc.rc"), "w").write(rc)
    print(f"make_retropc_res: icon and version {num} -> {os.path.relpath(out, ROOT)}")


main()
