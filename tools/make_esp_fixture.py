#!/usr/bin/env python3
"""make_esp_fixture.py -- build the EFI System Partition the ESP suite runs
against, shaped like the one on a Windows 11 laptop.

The point is the same as the FAT32 fixture's: this ESP is formatted by
mkfs.vfat and populated by mtools, so it is somebody else's idea of a
FAT32 volume, not ours. What the suite then proves is that installing into
it leaves every file Windows put there byte-for-byte identical -- and it
proves it by reading those files back with mtools as well as through our
own driver, because our driver agreeing with itself is not evidence.

Produces:

  tests/esp.img           100 MB FAT32, laid out like a Windows ESP
  tests/esp_full.img      a small ESP with almost no free space, so the
                          out-of-space refusal has something to refuse
  tests/esp_fixture.inc   the manifest: every file, its size and CRC, and
                          the geometry read back off the boot sector

The Microsoft files are filled with deterministic bytes rather than being
real binaries. What matters is that they are a few hundred KB of content
at known offsets which must not move by one byte, and a real bootmgfw.efi
would prove nothing extra.
"""
import os
import subprocess
import sys
import zlib

SECT = 512


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        sys.stderr.write("make_esp_fixture: failed: %s\n%s%s\n"
                         % (" ".join(cmd), r.stdout, r.stderr))
        sys.exit(1)
    return r.stdout


def need(tool):
    from shutil import which
    if which(tool) is None:
        sys.stderr.write(
            "make_esp_fixture: %s is not installed.\n"
            "  The ESP suite tests against a volume this project did not\n"
            "  format, so the formatter is a build dependency:\n"
            "      apt-get install dosfstools mtools\n" % tool)
        sys.exit(1)


def body(seed, size):
    out = bytearray(size)
    x = (seed * 2654435761) & 0xFFFFFFFF
    for i in range(size):
        x = (x * 1103515245 + 12345) & 0xFFFFFFFF
        out[i] = (x >> 16) & 0xFF
    return bytes(out)


# What a Windows 11 ESP actually holds, at roughly the right sizes.
# \EFI\Microsoft\ is the part that must not move by a byte.
DIRS = [
    "/EFI",
    "/EFI/Microsoft",
    "/EFI/Microsoft/Boot",
    "/EFI/Microsoft/Boot/Fonts",
    "/EFI/Microsoft/Boot/Resources",
    "/EFI/Microsoft/Recovery",
]

FILES = [
    ("/EFI/Microsoft/Boot/bootmgfw.efi",        body(1, 1_720_320)),
    ("/EFI/Microsoft/Boot/bootmgr.efi",         body(2, 1_679_360)),
    ("/EFI/Microsoft/Boot/BCD",                 body(3,    40_960)),
    ("/EFI/Microsoft/Boot/BCD.LOG",             body(4,    12_288)),
    ("/EFI/Microsoft/Boot/memtest.efi",         body(5, 1_138_688)),
    ("/EFI/Microsoft/Boot/Fonts/segoe_slboot.ttf", body(6, 93_204)),
    ("/EFI/Microsoft/Boot/Fonts/wgl4_boot.ttf", body(7,    45_056)),
    ("/EFI/Microsoft/Boot/Resources/bootres.dll", body(8, 102_400)),
    ("/EFI/Microsoft/Recovery/BCD",             body(9,    28_672)),
]


def geometry(img):
    with open(img, "rb") as f:
        b = f.read(SECT)
    u16 = lambda o: b[o] | (b[o + 1] << 8)
    u32 = lambda o: (b[o] | (b[o + 1] << 8) | (b[o + 2] << 16) | (b[o + 3] << 24))
    g = {
        "bytes_per_sect":  u16(11),
        "sects_per_clust": b[13],
        "rsvd_sects":      u16(14),
        "num_fats":        b[16],
        "fat_sz":          u16(22) or u32(36),
        "total_sects":     u16(19) or u32(32),
        "root_clus":       u32(44),
        "fsinfo_sect":     u16(48),
    }
    g["data_start"] = g["rsvd_sects"] + g["num_fats"] * g["fat_sz"]
    g["clusters"] = (g["total_sects"] - g["data_start"]) // g["sects_per_clust"]
    g["cluster_bytes"] = g["sects_per_clust"] * g["bytes_per_sect"]
    return g


def build(img, mb, files, dirs, label="SYSTEM"):
    if os.path.exists(img):
        os.unlink(img)
    with open(img, "wb") as f:
        f.truncate(mb * 1024 * 1024)
    # No partition table: this image IS the partition, the way the ESP is a
    # partition. The suite mounts it at LBA 0.
    run(["mkfs.vfat", "-F", "32", "-n", label, img])
    env = dict(os.environ, MTOOLS_SKIP_CHECK="1")
    for d in dirs:
        run(["mmd", "-i", img, "::" + d.lstrip("/")], env=env)
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        local = os.path.join(td, "f.bin")
        for p, data in files:
            with open(local, "wb") as f:
                f.write(data)
            run(["mcopy", "-i", img, "-o", local, "::" + p.lstrip("/")], env=env)


def emit(path, g, files):
    L = []
    a = L.append
    a("/* GENERATED by tools/make_esp_fixture.py -- do not edit.")
    a(" *")
    a(" * The manifest of tests/esp.img, emitted by the run that built it.")
    a(" * These are the files Windows put on its EFI System Partition, and")
    a(" * the whole claim of the ESP suite is that every one of them is")
    a(" * byte-for-byte identical after HavenDOS installs beside them.")
    a(" */")
    a("")
    a('#define ESP_IMG        "tests/esp.img"')
    a('#define ESP_IMG_FULL   "tests/esp_full.img"')
    for k in ("bytes_per_sect", "sects_per_clust", "rsvd_sects", "num_fats",
              "fat_sz", "total_sects", "root_clus", "fsinfo_sect",
              "data_start", "clusters", "cluster_bytes"):
        a("#define ESP_%-16s %d" % (k.upper(), g[k]))
    a("")
    a("typedef struct { const char *path; unsigned size; unsigned crc; } esp_file_t;")
    a("")
    a("static const esp_file_t ESP_FILES[] = {")
    for p, data in files:
        a('    {"%s", %u, 0x%08Xu},' % (p, len(data), zlib.crc32(data) & 0xFFFFFFFF))
    a("};")
    a("#define ESP_NFILES (int)(sizeof(ESP_FILES)/sizeof(ESP_FILES[0]))")
    a("")
    a("/* The deterministic body rule, so the suite can regenerate a file's")
    a("   expected bytes without the fixture shipping two megabytes of them. */")
    a("static void esp_body(unsigned seed, unsigned char *out, unsigned n){")
    a("    unsigned x = (unsigned)(seed * 2654435761u);")
    a("    for(unsigned i = 0; i < n; i++){")
    a("        x = x * 1103515245u + 12345u;")
    a("        out[i] = (unsigned char)((x >> 16) & 0xFF);")
    a("    }")
    a("}")
    a("static const unsigned ESP_SEEDS[] = {")
    a("    " + ", ".join(str(i + 1) for i in range(len(files))))
    a("};")
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "tests"
    for t in ("mkfs.vfat", "mcopy", "mmd"):
        need(t)

    img = os.path.join(out_dir, "esp.img")
    build(img, 100, FILES, DIRS)
    g = geometry(img)
    if g["clusters"] < 65525:
        sys.exit("make_esp_fixture: %d clusters is not FAT32" % g["clusters"])

    # A nearly-full ESP, so "not enough space" has something to refuse.
    # 34 MB with ~32 MB of filler leaves well under the ~1 MB the loader
    # needs, without being so small that mkfs refuses FAT32.
    full = os.path.join(out_dir, "esp_full.img")
    build(full, 34, [("/EFI/Microsoft/Boot/bootmgfw.efi", body(1, 1_720_320)),
                     ("/BIGFILLER.BIN", body(42, 31 * 1024 * 1024))],
          ["/EFI", "/EFI/Microsoft", "/EFI/Microsoft/Boot"], label="SYSTEM")

    emit(os.path.join(out_dir, "esp_fixture.inc"), g, FILES)

    total = sum(len(d) for _, d in FILES)
    print("make_esp_fixture: esp.img  %d clusters of %d bytes, %d files, %.1f MB of Windows"
          % (g["clusters"], g["cluster_bytes"], len(FILES), total / 1048576.0))
    gf = geometry(full)
    print("make_esp_fixture: esp_full.img  %d clusters, nearly full"
          % gf["clusters"])


if __name__ == "__main__":
    main()
