#!/usr/bin/env python3
"""Generate tests/appreg.inc from the app registry in shell/desktop.c.

tests/bars.inc is generated from shell/ui.c for the same reason: a test that
carries its own copy of the thing it is testing stops testing it the moment
the two drift, and drift between duplicated app tables is precisely the bug
the registry was introduced to kill.  So the counts come from the registry
itself, every build.

Usage: make_appreg_inc.py shell/desktop.c tests/appreg.inc
"""
import re, sys, collections

src, out = sys.argv[1], sys.argv[2]
text = open(src).read()

m = re.search(r'static const appreg_t appreg\[\]=\{(.*?)\n\};', text, re.S)
if not m:
    sys.exit("make_appreg_inc: cannot find appreg[] in " + src)

rows = re.findall(r'\{"([^"]+)",\s*"([^"]+)",\s*"(..)",\s*(\w+),\s*(CAT_\w+)\}',
                  m.group(1))
if not rows:
    sys.exit("make_appreg_inc: appreg[] parsed to zero entries")

ORDER = ["CAT_APPS", "CAT_SYSTEM", "CAT_HARDWARE", "CAT_GAMES",
         "CAT_MEDIA", "CAT_SETTINGS"]
counts = collections.Counter(r[4] for r in rows)

unknown = set(counts) - set(ORDER)
if unknown:
    sys.exit("make_appreg_inc: unknown category %s -- add it to ORDER here "
             "and to the test" % ", ".join(sorted(unknown)))

ids   = [r[0] for r in rows]
icons = [r[2] for r in rows]

with open(out, "w") as f:
    f.write("/* GENERATED by tools/make_appreg_inc.py from %s -- do not edit. */\n"
            % src)
    f.write("#define NREG_ACTUAL %d\n" % len(rows))
    f.write("#define NREALCAT %d\n" % len(ORDER))
    f.write("static const int CAT_N[NREALCAT] = { %s };\n"
            % ", ".join(str(counts[c]) for c in ORDER))
    f.write("static const char *CAT_NAME[NREALCAT] = { %s };\n"
            % ", ".join('"%s"' % c for c in ORDER))
    f.write("#define N_DISTINCT_IDS   %d\n" % len(set(ids)))
    f.write("#define N_DISTINCT_ICONS %d\n" % len(set(icons)))
    f.write("#define LONGEST_ID       %d\n" % max(len(i) for i in ids))
    f.write("#define SHORTEST_ICON    %d\n" % min(len(i) for i in icons))
    f.write("#define LONGEST_ICON     %d\n" % max(len(i) for i in icons))
    f.write("#define LONGEST_NAME     %d\n" % max(len(r[1]) for r in rows))

print("make_appreg_inc: %s -> %d apps across %d categories"
      % (out, len(rows), len(ORDER)))
