#!/usr/bin/env python3
"""make_font_ui.py -- IBM Plex Sans for the desktop (v0.9.8).

The desktop's own text -- the taskbar, the Start menu, window titles,
icon labels -- is set in IBM Plex Sans, the THS sans-serif, proportional
like any modern desktop. (The Terminal and the apps' grid keep Plex
Mono: include/font_aa.h.)

FreeType renders each size here, hinted, so the kernel only copies
coverage: no scaling at run time. Two weights, Regular and SemiBold, at
the sizes drivers/vga.c's wm_font_px() picks from (12 to 24 px). ASCII
plus Latin-1 letters. One byte of coverage a pixel, cropped to the ink.

    python3 tools/make_font_ui.py      -> include/font_ui.h
"""
import os
from PIL import Image, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "include", "font_ui.h")
FACES = [("plexsans-400.ttf", 0, (12, 13, 14, 16, 18, 20, 24)),
         ("plexsans-600.ttf", 1, (12, 13, 14, 16, 18, 20, 24))]
CHARS = list(range(32, 127)) + list(range(160, 256))


def main():
    lines = ["/* include/font_ui.h -- GENERATED by tools/make_font_ui.py, do not edit.",
             " * IBM Plex Sans (SIL Open Font License 1.1), Regular and SemiBold. */",
             "#ifndef FONT_UI_H", "#define FONT_UI_H", "#include \"types.h\"",
             "typedef struct { uint32_t off; uint8_t w, h; int8_t bx, by; uint8_t adv; } fui_glyph_t;",
             "typedef struct { uint8_t px, bold, ascent, height; const fui_glyph_t *g; const uint8_t *data; } fui_face_t;",
             "#define FUI_FIRST 32", "#define FUI_NCH 224"]
    faces = []
    for fname, bold, sizes in FACES:
        for px in sizes:
            font = ImageFont.truetype(os.path.join(HERE, "assets", fname), px)
            asc, desc = font.getmetrics()
            data = bytearray(); glyphs = []
            for cp in range(32, 256):
                if cp not in CHARS:
                    glyphs.append((0, 0, 0, 0, 0, 0)); continue
                ch = chr(cp)
                adv = int(round(font.getlength(ch)))
                bb = font.getbbox(ch)            # relative to the origin, top = ascent line
                if bb[2] <= bb[0] or bb[3] <= bb[1]:
                    glyphs.append((len(data), 0, 0, 0, 0, adv)); continue
                w, h = bb[2] - bb[0], bb[3] - bb[1]
                im = Image.new("L", (w, h), 0)
                from PIL import ImageDraw
                ImageDraw.Draw(im).text((-bb[0], -bb[1]), ch, font=font, fill=255)
                off = len(data)
                data += im.tobytes()
                glyphs.append((off, w, h, bb[0], bb[1], adv))
            tag = "fui_%d_%d" % (px, bold)
            lines.append("static const uint8_t %s_d[%d] = {" % (tag, max(1, len(data))))
            for i in range(0, len(data), 32):
                lines.append("    " + ",".join(str(b) for b in data[i:i + 32]) + ",")
            if not data:
                lines.append("0,")
            lines.append("};")
            lines.append("static const fui_glyph_t %s_g[FUI_NCH] = {" % tag)
            for (o, w, h, bx, by, adv) in glyphs:
                lines.append("    {%d,%d,%d,%d,%d,%d}," % (o, w, h, bx, by, adv))
            lines.append("};")
            faces.append("    {%d,%d,%d,%d,%s_g,%s_d}," % (px, bold, asc, asc + desc, tag, tag))
    lines.append("#define FUI_NFACES %d" % len(faces))
    lines.append("static const fui_face_t fui_faces[FUI_NFACES] = {")
    lines += faces
    lines += ["};", "#endif", ""]
    open(OUT, "w").write("\n".join(lines))
    print("wrote", OUT, len(faces), "faces")


if __name__ == "__main__":
    main()
