#!/usr/bin/env python3
"""
make_font_ext.py — compose the accented CP437 glyphs for the 8x8 text font

    python3 tools/make_font_ext.py include/font8x8.h include/font8x8_ext.h

WHY THIS EXISTS

font8x8.h leaves glyphs 128-255 blank; its header says HavenDOS "only ever
draws 7-bit ASCII". That was true until BOOT Chat started receiving UTF-8 from
phones, where "café", "naïve" and "Grüße" are ordinary text.

In 80x25 the BIOS font supplies the CP437 high range, so accented letters
already render there. The 8x8 font used by 80x50, 90x30 and 90x60 does not, so
without this the same message would show accents in one mode and blanks in
another — worse than either, because it looks like corruption.

HOW

Rather than hand-drawing thirty glyphs, each accented letter is composed from
the base letter already in the font plus an accent mark. Lowercase letters
occupy rows 3-7 and leave rows 0-2 empty, so a two-row accent drops in with no
distortion at all. Uppercase occupies rows 1-7, so its accent goes on row 0 and
sits tight against the letter — acceptable, and uppercase accents are rare.

Cedilla letters shift the base up one row to free row 7 for the tail.

Rows are MSB-first (bit 7 = leftmost), matching the pre-reversed convention
font8x8.h already uses, so the output goes straight into the VGA font plane.
"""

import re
import sys

# accent marks, as (row0, row1) drawn above the letter
DIAERESIS  = (0x00, 0x66)   # ..##..##.
ACUTE      = (0x0C, 0x18)   # rises to the right
GRAVE      = (0x30, 0x18)   # rises to the left
CIRCUMFLEX = (0x18, 0x24)   # caret
TILDE      = (0x00, 0x36)   # small wave
RING       = (0x18, 0x18)   # stub ring

CEDILLA_ROW = 0x18          # tail, drawn on row 7

# CP437 code -> (base ASCII letter, accent, kind)
#   kind: "above" = accent on rows 0-1, base untouched
#         "cedilla" = base shifted up one row, tail on row 7
GLYPHS = {
    0x80: ("C", None,       "cedilla"),
    0x81: ("u", DIAERESIS,  "above"),
    0x82: ("e", ACUTE,      "above"),
    0x83: ("a", CIRCUMFLEX, "above"),
    0x84: ("a", DIAERESIS,  "above"),
    0x85: ("a", GRAVE,      "above"),
    0x86: ("a", RING,       "above"),
    0x87: ("c", None,       "cedilla"),
    0x88: ("e", CIRCUMFLEX, "above"),
    0x89: ("e", DIAERESIS,  "above"),
    0x8A: ("e", GRAVE,      "above"),
    0x8B: ("i", DIAERESIS,  "above"),
    0x8C: ("i", CIRCUMFLEX, "above"),
    0x8D: ("i", GRAVE,      "above"),
    0x8E: ("A", DIAERESIS,  "above"),
    0x8F: ("A", RING,       "above"),
    0x90: ("E", ACUTE,      "above"),
    0x93: ("o", CIRCUMFLEX, "above"),
    0x94: ("o", DIAERESIS,  "above"),
    0x95: ("o", GRAVE,      "above"),
    0x96: ("u", CIRCUMFLEX, "above"),
    0x97: ("u", GRAVE,      "above"),
    0x98: ("y", DIAERESIS,  "above"),
    0x99: ("O", DIAERESIS,  "above"),
    0x9A: ("U", DIAERESIS,  "above"),
    0xA0: ("a", ACUTE,      "above"),
    0xA1: ("i", ACUTE,      "above"),
    0xA2: ("o", ACUTE,      "above"),
    0xA3: ("u", ACUTE,      "above"),
    0xA4: ("n", TILDE,      "above"),
    0xA5: ("N", TILDE,      "above"),
    0xE1: ("B", None,       "sharps"),      # ß, drawn as its own shape below
}

SHARP_S = [0x00, 0x00, 0x7C, 0x66, 0x6C, 0x66, 0x66, 0x6C]   # ß


def read_font(path):
    text = open(path).read()
    vals = [int(v, 16) for v in re.findall(r"0x([0-9A-Fa-f]{2})", text)]
    if len(vals) < 256 * 8:
        raise SystemExit("font table too short: %d bytes" % len(vals))
    return [vals[i * 8:(i + 1) * 8] for i in range(256)]


def compose(font, base, accent, kind):
    rows = list(font[ord(base)])

    if kind == "sharps":
        return SHARP_S

    if kind == "cedilla":
        # shift the letter up one row, hang the tail off row 7
        rows = rows[1:] + [0x00]
        rows[7] = CEDILLA_ROW
        return rows

    lower = base.islower()
    if lower:
        # rows 0-2 are empty for lowercase: the accent drops straight in
        rows[0] = accent[0]
        rows[1] = accent[1]
    else:
        # uppercase reaches row 1, so only row 0 is free; OR the marks in so
        # nothing of the letter is lost if they touch
        rows[0] |= accent[0] | accent[1]
    return rows


def main():
    if len(sys.argv) != 3:
        print(__doc__.strip())
        return 1
    font = read_font(sys.argv[1])

    out = []
    out.append("/*")
    out.append(" * font8x8_ext.h - accented CP437 glyphs for the 8x8 text font")
    out.append(" *")
    out.append(" * GENERATED by tools/make_font_ext.py - do not edit by hand.")
    out.append(" *")
    out.append(" * font8x8.h leaves 128-255 blank. These are composed from the base")
    out.append(" * letters already in that table plus an accent mark, so accented text")
    out.append(" * renders identically in 80x25 (BIOS font) and in the 8-row modes.")
    out.append(" */")
    out.append("#pragma once")
    out.append('#include "types.h"')
    out.append("")
    out.append("typedef struct { uint8_t idx; uint8_t rows[8]; } font_ext_glyph_t;")
    out.append("")
    out.append("static const font_ext_glyph_t FONT8X8_EXT[] = {")
    for code in sorted(GLYPHS):
        base, accent, kind = GLYPHS[code]
        rows = compose(font, base, accent, kind)
        body = ",".join("0x%02X" % r for r in rows)
        out.append("    {0x%02X,{%s}},   /* %s + %s */" % (code, body, base, kind))
    out.append("};")
    out.append("")
    out.append("#define FONT8X8_EXT_N ((int)(sizeof(FONT8X8_EXT)/sizeof(FONT8X8_EXT[0])))")
    out.append("")

    open(sys.argv[2], "w").write("\n".join(out))
    print("wrote %s: %d glyphs" % (sys.argv[2], len(GLYPHS)))

    # ASCII preview so a bad accent is visible at build time, not on hardware
    for code in (0x89, 0x82, 0x94, 0x81, 0xA4, 0x8E):
        base, accent, kind = GLYPHS[code]
        rows = compose(font, base, accent, kind)
        print("0x%02X (%s):" % (code, base))
        for r in rows:
            print("   " + "".join("#" if r & (1 << (7 - b)) else "." for b in range(8)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
