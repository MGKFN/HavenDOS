#!/usr/bin/env python3
"""make_fat32_fixture.py -- build the disk images the FAT32 suite runs against.

WHY THIS EXISTS, AND WHY IT IS NOT OPTIONAL

tests/test_fat16path.c has never run.  It skips unless BOOTDISK names an
installer-produced image, no such image is in the tree, and the skip notice
was being swallowed by a `tail -1` in the Makefile -- so the suite appeared
in `make test` output with no result and nobody noticed for three releases.

The rule that produces: a fixture a suite needs must be GENERATED BY THE
BUILD, or the suite is decoration.  So this script is a prerequisite of the
FAT32 suite in the Makefile, the suite FAILS rather than skips when the image
is absent, and the manifest the suite checks against is emitted from the same
run that writes the image.  Two copies of a list drift; there is one copy.

WHAT IT PRODUCES

  tests/fat32.img          64 MB, MBR + one FAT32 partition at LBA 2048,
                           formatted by mkfs.vfat and populated by mcopy --
                           i.e. by somebody else's FAT32 implementation, which
                           is the entire point of testing against it
  tests/fat16.img          16 MB FAT16, for type detection only
  tests/fat12.img          1.4 MB FAT12, for type detection only
  tests/fat32_fixture.inc  the manifest: every file, its bytes or its CRC,
                           and the geometry mkfs ACTUALLY chose, read back off
                           the image rather than assumed

The geometry being read back matters.  A test that asserts the driver parsed
"the sectors-per-cluster I passed to mkfs" proves the driver agrees with this
script.  A test that asserts it parsed "the sectors-per-cluster that is in the
boot sector on disk" proves the driver agrees with mkfs.vfat, which is the
claim worth making.
"""
import os
import subprocess
import sys
import zlib

SECT = 512
PART_LBA = 2048                 # matches fs/fat16.c's FAT16_PART_LBA layout


def run(cmd, **kw):
    r = subprocess.run(cmd, capture_output=True, text=True, **kw)
    if r.returncode != 0:
        sys.stderr.write("make_fat32_fixture: command failed: %s\n" % " ".join(cmd))
        sys.stderr.write(r.stdout + r.stderr)
        sys.exit(1)
    return r.stdout


def need(tool):
    from shutil import which
    if which(tool) is None:
        sys.stderr.write(
            "make_fat32_fixture: %s is not installed.\n"
            "  The FAT32 suite tests against an image this project did not\n"
            "  format, so the formatter is a build dependency:\n"
            "      apt-get install dosfstools mtools\n" % tool)
        sys.exit(1)


# ---------------------------------------------------------------- content ---
# File bodies are deterministic so the suite can compare byte for byte.  Small
# files are emitted into the .inc verbatim; large ones as a CRC, so the header
# stays readable.  Nothing about the content rule is duplicated in C.
def body(seed, size):
    out = bytearray(size)
    x = (seed * 2654435761) & 0xFFFFFFFF
    for i in range(size):
        x = (x * 1103515245 + 12345) & 0xFFFFFFFF
        out[i] = (x >> 16) & 0xFF
    return bytes(out)


def text(s):
    return s.encode("ascii")


# (path on the image, bytes)  -- paths use / and are what the DRIVER is asked
# for; mcopy is given the ::-form separately.
FILES = [
    # a plain 8.3 name, the easy case
    ("/HELLO.TXT",           text("Hello from mkfs.vfat.\n")),
    # a long name with spaces and mixed case: needs LFN reassembly, and the
    # short name beside it will be mangled with a ~1 tail
    ("/A Long File Name.txt", text("long name, read through LFN entries\n")),
    # lower case throughout -- mkfs/mcopy may store this with the NT case
    # flags rather than an LFN, which is a different read path
    ("/readme.md",           text("# readme\nlower case 8.3\n")),
    # the shape FAT16 gets wrong: name_to_83() turns a leading dot into a
    # BLANK basename with extension CON.  This file is here so the FAT32
    # driver is proved not to inherit that.
    ("/.config",             text("leading dot, not a blank basename\n")),
    ("/.shell_history",      text("ls\ndmesg\nusb -vv\n")),
    # a name whose first eight characters collide with another, so the ~N
    # uniquifier has something to disambiguate
    ("/configuration-one.cfg", text("first of two colliding basenames\n")),
    ("/configuration-two.cfg", text("second of two colliding basenames\n")),
    # spans many clusters at 512 bytes per cluster: the chain walk, not a
    # single-cluster read dressed up as one
    ("/BIG.BIN",             body(7, 64 * 1024)),
    # exactly one cluster, and exactly one cluster plus one byte: the two
    # off-by-one cases in every chain walk ever written
    ("/EXACT.BIN",           body(11, 512)),
    ("/PLUSONE.BIN",         body(13, 513)),
    ("/EMPTY.TXT",           b""),
    # the ESP shape Phase B has to write into
    ("/EFI/BOOT/BOOTX64.EFI", body(17, 9000)),
    ("/EFI/HAVENDOS/README.TXT", text("HavenDOS lives here\n")),
    ("/EFI/HAVENDOS/grub.cfg", text("set timeout=5\n")),
]

DIRS = ["/EFI", "/EFI/BOOT", "/EFI/HAVENDOS", "/MANY"]

# Enough entries in one directory to push it past a single cluster.  At 512
# bytes per cluster a directory cluster holds 16 entries, and each of these
# needs an LFN slot as well, so 120 files is several clusters of chain.
MANY = 120


def build_image(path, mb, fatbits, extra_mkfs=()):
    total = mb * 1024 * 1024 // SECT
    with open(path, "wb") as f:
        f.truncate(total * SECT)
    part_sects = total - PART_LBA
    # MBR: one partition, LBA-addressed, spanning the rest of the disk.
    mbr = bytearray(SECT)
    ptype = {32: 0x0C, 16: 0x0E, 12: 0x01}[fatbits]
    e = 446
    mbr[e + 0] = 0x80                      # bootable
    mbr[e + 1], mbr[e + 2], mbr[e + 3] = 0xFE, 0xFF, 0xFF   # CHS, maxed out
    mbr[e + 4] = ptype
    mbr[e + 5], mbr[e + 6], mbr[e + 7] = 0xFE, 0xFF, 0xFF
    for i in range(4):
        mbr[e + 8 + i] = (PART_LBA >> (8 * i)) & 0xFF
        mbr[e + 12 + i] = (part_sects >> (8 * i)) & 0xFF
    mbr[510], mbr[511] = 0x55, 0xAA
    with open(path, "r+b") as f:
        f.write(mbr)
    run(["mkfs.vfat", "-F", str(fatbits), "-n", "HAVENFIX",
         "--offset", str(PART_LBA), *extra_mkfs, path, str(part_sects // 2)])
    return part_sects


def mcopy_into(img, files, dirs):
    """Populate through mtools, which talks to the partition at an offset."""
    drive = "%s@@%d" % (img, PART_LBA * SECT)
    env = dict(os.environ, MTOOLS_SKIP_CHECK="1")
    for d in dirs:
        run(["mmd", "-i", drive, "::" + d.lstrip("/")], env=env)
    import tempfile
    with tempfile.TemporaryDirectory() as td:
        for p, data in files:
            local = os.path.join(td, "f.bin")
            with open(local, "wb") as f:
                f.write(data)
            run(["mcopy", "-i", drive, "-o", local, "::" + p.lstrip("/")], env=env)


# ------------------------------------------------------------- read-back ----
def u16(b, o):
    return b[o] | (b[o + 1] << 8)


def u32(b, o):
    return b[o] | (b[o + 1] << 8) | (b[o + 2] << 16) | (b[o + 3] << 24)


def geometry(img):
    """Read the geometry mkfs.vfat actually wrote, the same way the driver
       will.  Nothing here is taken from what we passed on the command line."""
    with open(img, "rb") as f:
        f.seek(PART_LBA * SECT)
        b = f.read(SECT)
    g = {
        "bytes_per_sect":  u16(b, 11),
        "sects_per_clust": b[13],
        "rsvd_sects":      u16(b, 14),
        "num_fats":        b[16],
        "root_ent_cnt":    u16(b, 17),
        "fat_sz16":        u16(b, 22),
        "tot_sec16":       u16(b, 19),
        "tot_sec32":       u32(b, 32),
        "fat_sz32":        u32(b, 36),
        "root_clus":       u32(b, 44),
        "fsinfo_sect":     u16(b, 48),
    }
    # The 16-bit field decides, and only when it is zero does the 32-bit one
    # mean anything.  Offset 36 is BPB_FATSz32 on FAT32 and the start of the
    # FAT12/16 extended boot record (BS_DrvNum, BS_VolID, BS_VolLab...) on
    # everything else, so reading it first gives a FAT size of 1529413760
    # sectors on a 16 MB FAT16 volume.  Same shape of trap at offset 32 for
    # the total sector count.  fs/fat32.c has the same rule for the same
    # reason; this is where it was found.
    fatsz = g["fat_sz16"] or g["fat_sz32"]
    tot = g["tot_sec16"] or g["tot_sec32"]
    rootsects = (g["root_ent_cnt"] * 32 + g["bytes_per_sect"] - 1) // g["bytes_per_sect"]
    datastart = g["rsvd_sects"] + g["num_fats"] * fatsz + rootsects
    g["fat_sz"] = fatsz
    g["total_sects"] = tot
    g["data_start"] = datastart
    g["clusters"] = (tot - datastart) // g["sects_per_clust"]
    return g


def c_bytes(data):
    return ",".join(str(x) for x in data)


def emit(path, g32, g16, g12, files, dirs, many):
    L = []
    a = L.append
    a("/* GENERATED by tools/make_fat32_fixture.py -- do not edit.")
    a(" *")
    a(" * The manifest of tests/fat32.img, emitted by the same run that wrote")
    a(" * the image, so the suite cannot certify a stale copy of what it is")
    a(" * checking.  The geometry below was READ BACK off the boot sector, not")
    a(" * taken from the mkfs command line: the claim worth making is that the")
    a(" * driver agrees with mkfs.vfat, not that it agrees with this script.")
    a(" */")
    a("")
    a("#define FIX_IMG            \"tests/fat32.img\"")
    a("#define FIX_IMG16          \"tests/fat16.img\"")
    a("#define FIX_IMG12          \"tests/fat12.img\"")
    a("#define FIX_PART_LBA       %d" % PART_LBA)
    a("")
    for k in ("bytes_per_sect", "sects_per_clust", "rsvd_sects", "num_fats",
              "root_ent_cnt", "fat_sz", "total_sects", "data_start",
              "root_clus", "fsinfo_sect", "clusters"):
        a("#define FIX_%-18s %d" % (k.upper(), g32[k]))
    a("#define FIX_%-18s %d" % ("CLUSTER_BYTES",
                                g32["sects_per_clust"] * g32["bytes_per_sect"]))
    a("")
    a("/* the two volumes that exist only so type detection has something to")
    a("   get wrong: both are small, neither is FAT32, and the partition type")
    a("   byte in their MBR deliberately disagrees with nothing -- it is the")
    a("   CLUSTER COUNT that has to decide. */")
    a("#define FIX16_CLUSTERS     %d" % g16["clusters"])
    a("#define FIX12_CLUSTERS     %d" % g12["clusters"])
    a("")
    a("typedef struct {")
    a("    const char    *path;      /* as the driver is asked for it      */")
    a("    unsigned       size;")
    a("    unsigned       crc;       /* CRC-32, zlib/GPT polynomial        */")
    a("    const unsigned char *bytes;  /* NULL when the file is large     */")
    a("} fix_file_t;")
    a("")
    for i, (p, data) in enumerate(files):
        if len(data) <= 256 and data:
            a("static const unsigned char fix_b%d[] = {%s};" % (i, c_bytes(data)))
    a("")
    a("static const fix_file_t FIX_FILES[] = {")
    for i, (p, data) in enumerate(files):
        small = len(data) <= 256 and data
        a('    {"%s", %u, 0x%08Xu, %s},'
          % (p, len(data), zlib.crc32(data) & 0xFFFFFFFF,
             ("fix_b%d" % i) if small else "0"))
    a("};")
    a("#define FIX_NFILES  (int)(sizeof(FIX_FILES)/sizeof(FIX_FILES[0]))")
    a("")
    a("static const char *FIX_DIRS[] = {")
    for d in dirs:
        a('    "%s",' % d)
    a("};")
    a("#define FIX_NDIRS   (int)(sizeof(FIX_DIRS)/sizeof(FIX_DIRS[0]))")
    a("")
    a("/* /MANY holds this many files named many-0001.txt .. ; enough that the")
    a("   directory is a cluster CHAIN rather than one cluster, which is the")
    a("   thing a root directory stops being on FAT32. */")
    a("#define FIX_MANY    %d" % many)
    with open(path, "w") as f:
        f.write("\n".join(L) + "\n")


def main():
    out_dir = sys.argv[1] if len(sys.argv) > 1 else "tests"
    for t in ("mkfs.vfat", "mcopy", "mmd"):
        need(t)
    img32 = os.path.join(out_dir, "fat32.img")
    img16 = os.path.join(out_dir, "fat16.img")
    img12 = os.path.join(out_dir, "fat12.img")

    # 512-byte clusters so that a 64 KB file is a 128-link chain and a
    # directory of 120 long-named files spans several clusters.  A fixture
    # whose every file fits in one cluster cannot fail a chain walk.
    build_image(img32, 64, 32, extra_mkfs=("-s", "1"))
    build_image(img16, 16, 16)
    build_image(img12, 2, 12, extra_mkfs=("-s", "1"))

    files = list(FILES)
    for i in range(1, MANY + 1):
        files.append(("/MANY/many-%04d.txt" % i,
                      text("entry %d of %d\n" % (i, MANY))))
    mcopy_into(img32, files, DIRS)

    g32, g16, g12 = geometry(img32), geometry(img16), geometry(img12)
    if g32["clusters"] < 65525:
        sys.stderr.write("make_fat32_fixture: %d clusters is not FAT32\n"
                         % g32["clusters"])
        sys.exit(1)
    if not (4085 <= g16["clusters"] < 65525):
        sys.stderr.write("make_fat32_fixture: fat16.img has %d clusters, "
                         "which is not FAT16\n" % g16["clusters"])
        sys.exit(1)
    if g12["clusters"] >= 4085:
        sys.stderr.write("make_fat32_fixture: fat12.img has %d clusters, "
                         "which is not FAT12\n" % g12["clusters"])
        sys.exit(1)

    # Only the hand-written files go in the manifest; the 120 in /MANY are
    # checked by rule, not one by one.
    emit(os.path.join(out_dir, "fat32_fixture.inc"),
         g32, g16, g12, FILES, DIRS, MANY)

    print("make_fat32_fixture: fat32.img  %d clusters of %d sectors, "
          "root at cluster %d, FAT %d sectors"
          % (g32["clusters"], g32["sects_per_clust"], g32["root_clus"],
             g32["fat_sz"]))
    print("make_fat32_fixture: fat16.img  %d clusters   fat12.img  %d clusters"
          % (g16["clusters"], g12["clusters"]))
    print("make_fat32_fixture: %d files + %d in /MANY, %d directories"
          % (len(FILES), MANY, len(DIRS)))


if __name__ == "__main__":
    main()
